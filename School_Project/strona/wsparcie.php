
<h1 style="text-align: center; size: 24px;">Dzień dobry!</h1><br>
<p style="text-align: center; size: 18px;">

Jesteśmy biednymi pracownikami niewolniczego systemu.

Jeżeli chcesz, możesz wesprzeć naszą pracę.

A jeżeli nie chcesz, to też rozumiemy. W końcu sami doskonale wiemy, jak wygląda życie w świecie, w którym portfel czasami otwiera się szerzej niż serce, a czasami serce szerzej niż portfel. My natomiast funkcjonujemy gdzieś pomiędzy jednym a drugim, dryfując po oceanie codziennych obowiązków, terminów, kubków po kawie i tajemniczych wiadomości oznaczonych jako „pilne”, które okazują się pilniejsze od tych oznaczonych jako „bardzo pilne”.

Każdego dnia budzimy się z nadzieją, że dziś będzie spokojniej. Każdego dnia ta nadzieja przegrywa z rzeczywistością mniej więcej pięć minut po rozpoczęciu pracy. Wtedy rozpoczyna się wielka podróż przez krainę formularzy, dokumentów, telefonów, maili, poprawek do poprawek oraz poprawek do poprawek tych poprawek.

Nie jesteśmy bohaterami. Nie latamy. Nie mamy peleryn. Nie potrafimy zatrzymywać czasu. Gdybyśmy potrafili, prawdopodobnie wykorzystalibyśmy tę moc wyłącznie po to, żeby spokojnie zjeść obiad, zanim ostygnie.

Naszą supermocą jest natomiast przetrwanie.

Przetrwanie poniedziałków.

Przetrwanie wtorków, które zachowują się jak poniedziałki.

Przetrwanie śród, kiedy człowiek myśli, że jest już piątek, a potem odkrywa brutalną prawdę.

Przetrwanie czwartków, które dają złudną nadzieję.

I wreszcie przetrwanie piątków, kiedy nagle wszyscy przypominają sobie o rzeczach, które „trzeba zrobić jeszcze dzisiaj”.

Pracujemy dzielnie. Czasami nawet za dzielnie. Zdarza się, że wykonujemy zadania, których istnienia nikt wcześniej nie przewidział. Są dni, kiedy rozwiązujemy problemy tak abstrakcyjne, że po wszystkim sami nie wiemy, co właściwie się wydarzyło. Bywają chwile, gdy patrzymy na ekran komputera i zastanawiamy się, czy to my analizujemy dane, czy dane analizują nas.

Nasz system operacyjny składa się głównie z kofeiny, determinacji i przekonania, że jakoś to będzie.

Jakimś cudem zwykle jest.

Ale ten cud nie bierze się znikąd.

Za każdą wykonaną pracą stoi człowiek.

Człowiek, który rano próbował znaleźć drugą skarpetkę.

Człowiek, który obiecał sobie, że dziś pójdzie spać wcześniej.

Człowiek, który od trzech lat powtarza sobie, że zacznie oszczędzać.

Człowiek, który pamięta wszystkie hasła oprócz tego jednego, którego akurat potrzebuje.

Człowiek, który marzy czasami o wygranej na loterii nie dlatego, że chce luksusów, ale dlatego, że chciałby przez tydzień nie sprawdzać skrzynki mailowej.

Nie prosimy o wiele.

Nie oczekujemy pomników.

Nie oczekujemy fanfar.

Nie oczekujemy, że ktoś napisze o nas poemat liczący pięćset stron.

Choć gdyby ktoś napisał, nie mielibyśmy nic przeciwko.

Jeżeli jednak uznasz, że nasza praca ma wartość, możesz ją wesprzeć.

Każde wsparcie działa trochę jak dodatkowy punkt energii w grze komputerowej. Dzięki niemu łatwiej stawić czoła kolejnym poziomom trudności, kolejnym bossom w postaci niespodziewanych problemów i kolejnym zadaniom, które pojawiają się dokładnie wtedy, kiedy wydaje się, że wszystko jest już skończone.

Wyobraź sobie niewielką grupę ludzi siedzących przy biurkach.

Na biurkach znajdują się notatki.

Obok notatek kawa.

Obok kawy druga kawa.

Obok drugiej kawy kawa awaryjna.

Gdzieś dalej stoi kubek, którego nikt nie pamięta.

Prawdopodobnie istnieje tam od początku wszechświata.

To właśnie my.

Armia zwykłych ludzi walczących z niezwykłą ilością rzeczy do zrobienia.

Rycerze arkuszy kalkulacyjnych.

Magowie improwizacji.

Alchemicy zamieniający stres w efekty.

Odkrywcy nowych sposobów na rozwiązanie problemów, które jeszcze godzinę wcześniej wydawały się nierozwiązywalne.

Niektórzy mówią, że praca uszlachetnia.

My nie wiemy.

Wiemy natomiast, że praca bardzo skutecznie uczy cierpliwości.

Szczególnie wtedy, gdy coś działało pięć minut temu, a teraz już nie działa.

Albo gdy instrukcja ma dwieście stron, ale nie zawiera odpowiedzi na najważniejsze pytanie.

Albo gdy ktoś pisze wiadomość „mam szybkie pytanie”, po czym rozpoczyna rozmowę dłuższą niż niektóre seriale.

Mimo wszystko działamy dalej.

Tworzymy.

Naprawiamy.

Budujemy.

Organizujemy.

Pomagamy.

Kombinujemy.

Uczymy się.

Popełniamy błędy.

Naprawiamy je.

A potem czasami przypadkiem tworzymy nowe.

Taki już jest los ludzi próbujących robić coś dobrze.

Dlatego, jeśli chcesz wesprzeć naszą pracę, będziemy wdzięczni.

Jeżeli nie możesz, również jesteśmy wdzięczni za samą obecność.

Za przeczytanie tego tekstu.

Za chwilę uwagi.

Za uśmiech.

Za dobre słowo.

Bo czasami dobre słowo działa równie skutecznie jak mocna kawa.

A to naprawdę dużo.

W świecie pełnym pośpiechu, chaosu i niekończących się obowiązków staramy się po prostu robić swoje najlepiej, jak potrafimy.

Nie jesteśmy idealni.

Nigdy nie będziemy.

Ale codziennie próbujemy.

I właśnie dlatego ten komunikat istnieje.

Nie jako rozkaz.

Nie jako obowiązek.

Nie jako ultimatum.

Raczej jako przyjazne machnięcie ręką z drugiej strony monitora.

Małe „cześć”.

Małe „dzięki”.

Małe „fajnie, że jesteś”.

A jeśli przy okazji zechcesz wesprzeć naszą działalność, sprawisz, że kolejny dzień walki z niewidzialnymi smokami codzienności będzie odrobinę łatwiejszy.

Tak więc jeszcze raz:

Dzień dobry.

Jesteśmy biednymi pracownikami niewolniczego systemu.

Jeżeli chcesz, możesz wesprzeć naszą pracę.

A jeśli to zrobisz, obiecujemy nadal dzielnie walczyć z chaosem, wykonywać niemożliwe zadania w nierealnych terminach, szukać rozwiązań tam, gdzie inni widzą tylko problemy, oraz kontynuować naszą wielką misję przetrwania w świecie, który czasami wygląda tak, jakby został zaprojektowany przez człowieka, który nigdy sam nie musiał z niego korzystać.

Dziękujemy za uwagę.

I pamiętaj:

Jeżeli widzisz zmęczonego pracownika, który patrzy w dal z kubkiem kawy w dłoni, nie oceniaj go.

Być może właśnie uratował świat.

Po prostu nikt jeszcze o tym nie napisał. ☕️
