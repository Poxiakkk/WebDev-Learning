<p># Kontakt

Witamy w sekcji kontaktowej. Tak, to właśnie tutaj znajduje się kontakt. Jeżeli tu trafiłeś, oznacza to, że prawdopodobnie chcesz się z nami skontaktować, albo kliknąłeś przypadkiem, albo testujesz czy ta strona działa, albo jesteś osobą, która zawsze czyta wszystko od początku do końca i za chwilę odkryje, że ten tekst jest niepotrzebnie długi.

Kontakt jest dla nas niezwykle ważny. Nie tylko ważny. Bardzo ważny. Tak ważny, że stworzyliśmy osobną stronę tylko po to, żeby poinformować Cię, że możesz się z nami skontaktować.

Jeżeli masz pytania — napisz.
Jeżeli masz odpowiedzi — też napisz.
Jeżeli nie masz pytań ani odpowiedzi, ale chcesz coś powiedzieć — nadal możesz napisać.
Jeżeli nie wiesz co napisać — napisz „hej”.
Jeżeli nie chcesz pisać — to trochę utrudnia kontakt, ale szanujemy decyzję.

## Jak się z nami skontaktować?

Możesz użyć formularza kontaktowego znajdującego się poniżej. Formularz został zaprojektowany specjalnie po to, abyś mógł wpisać swoje dane i wiadomość. Nie jest to przypadkowy zestaw pól — każde pole ma swoje zadanie.

### Imię

Tutaj wpisujesz swoje imię.
Nie cudze.
Chyba że piszesz za kogoś.
Ale wtedy dobrze byłoby to zaznaczyć.

### Adres e-mail

Tutaj wpisujesz adres e-mail.
Prawdziwy.
Nie taki typu:
„[nieodpisujcie@prosze.com](mailto:nieodpisujcie@prosze.com)”
bo wtedy kontakt staje się jednostronnym eksperymentem społecznym.

### Temat wiadomości

Temat pomaga nam zrozumieć, czego dotyczy wiadomość.

Przykłady dobrych tematów:
– Pytanie
– Problem
– Oferta
– Pomoc
– Czy to działa

Przykłady mniej dobrych:
– AAAAAAAAAA
– ??
– zgadnij
– pilne
– przeczytaj

### Treść wiadomości

Tutaj dzieje się magia.
Możesz napisać wszystko.
No prawie wszystko.
Im więcej szczegółów podasz, tym większa szansa, że odpowiedź nie będzie brzmiała:
„Czy możesz doprecyzować?”

Nie musisz pisać formalnie.

Przykład:
„Cześć, mam pytanie.”

też działa.

Nie trzeba zaczynać od:
„Szanowni Państwo, w związku z zaistniałą sytuacją…”

Chociaż można.

## Kiedy odpowiadamy?

Odpowiadamy możliwie szybko.

Co oznacza „możliwie szybko”?

To zależy.

Czas jest pojęciem względnym.

Dla człowieka:
10 minut.

Dla osoby czekającej na odpowiedź:
3 dni.

Dla internetu:
0,3 sekundy.

Dla aktualizacji systemu:
za 5 minut (około 2 godzin).

## Co jeśli nie odpowiemy?

Najpierw sprawdź:
– czy wiadomość została wysłana,
– czy podałeś poprawny kontakt,
– czy odpowiedź nie siedzi w spamie,
– czy przypadkiem nie wysłałeś wiadomości do siebie.

Jeżeli wszystko jest dobrze — napisz ponownie.

Nie obrażamy się za przypomnienia.

No chyba że przypomnienie wygląda tak:

„halo”
po 2 minutach:
„???"
po 4 minutach:
„serio”
po 5 minutach:
„obsługa tragedia”

## Czy czytamy wszystkie wiadomości?

Tak.

Niektóre nawet kilka razy.

Czasami czytamy wiadomość, myślimy nad odpowiedzią, potem otwieramy ją drugi raz, potem trzeci raz i nagle okazuje się, że minęło pół dnia.

## Kontakt awaryjny

Jeżeli sprawa jest pilna:
napisz.

Jeżeli nie jest pilna:
też napisz.

Jeżeli nie jesteś pewny:
napisz i zaznacz, że nie wiesz.

## Dodatkowe informacje

Nie odpowiadamy telepatycznie.
Nie odbieramy sygnałów kosmicznych.
Nie analizujemy kropek w wiadomościach.
Nie wiemy co oznacza „musimy pogadać” bez kontekstu.
Nie jesteśmy w stanie zgadnąć problemu po wiadomości:
„ej”.

## Podsumowanie

Jeżeli dotarłeś do końca tej strony kontaktowej, prawdopodobnie bardziej zależało Ci na czytaniu niż na kontakcie.

Ale skoro już tu jesteś…

napisz.

Po to istnieje ta strona.

I formularz.

I internet.

I litery.

I klawiatura.

I przycisk „Wyślij”.

A jeżeli nadal nie wiesz co zrobić —
to znaczy, że właśnie przeczytałeś kilkaset słów o kontakcie zamiast po prostu się skontaktować.

Zapraszamy.
